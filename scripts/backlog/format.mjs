// Parse and render plans/backlog.md. Pure: no git, no file system.
//
// The file has three parts:
//   1. a preamble (title, how to use it, the PRD board): kept verbatim;
//   2. "## Summary": a table regenerated on every write;
//   3. "## Items": one block per item, in id order:
//
//      ### B-12 · bug · Sign-in can be submitted twice
//      - status: triaged
//      - prd: quick-fixes
//      - owner: prd/quick-fixes
//      - commit: 1a2b3c4
//
//      Free notes (any Markdown) until the next item.

export const TYPES = ["bug", "change", "feature", "plan", "question", "chore"];
export const STATUSES = ["inbox", "triaged", "in-progress", "ready", "landed", "staging", "live", "dropped"];
export const FIELDS = ["status", "prd", "owner", "commit"];
/** Statuses worked out from git once an item has a commit. */
export const DERIVED = ["ready", "landed", "staging", "live"];
/** Finished: `archive` moves these to plans/backlog-archive.md. */
export const FINISHED = ["landed", "staging", "live", "dropped"];

/** The archive's preamble, when `archive` creates it. */
export const ARCHIVE_PREAMBLE = [
  "# Backlog archive",
  "",
  "Finished items (landed, staging, live and dropped), moved here from [backlog.md](backlog.md) by `pnpm backlog archive`, with their notes; their inbox lines were removed. `pnpm backlog show B-n` and `pnpm backlog list --all` still find them. Don't edit it by hand.",
].join("\n");

const SUMMARY = "## Summary";
const ITEMS = "## Items";
const GENERATED = "<!-- Generated by `pnpm backlog` on every write: don't edit this table by hand. -->";
const HEADING = /^### (B-\d+) · (\S+) · (.*)$/;
const FIELD = new RegExp(`^- (${FIELDS.join("|")}):[ \\t]*(.*)$`);

export class BacklogError extends Error {}

/** @typedef {{ id: string, type: string, title: string, status: string, prd: string, owner: string, commit: string, notes: string }} Item */
/** @typedef {{ preamble: string, items: Item[], reserved?: string[], archived?: string[] }} Backlog */

/**
 * @param {string} text
 * @param {{ lenient?: boolean }} [opts] lenient: keep duplicate ids (for `doctor`) instead of refusing them
 * @returns {Backlog}
 */
export function parse(text, opts = {}) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const at = (h) => lines.findIndex((l) => l.trim() === h);
  const itemsAt = at(ITEMS);
  if (itemsAt < 0) throw new BacklogError(`backlog.md has no "${ITEMS}" heading`);
  const summaryAt = at(SUMMARY);
  const preambleEnd = summaryAt >= 0 && summaryAt < itemsAt ? summaryAt : itemsAt;
  const preamble = lines.slice(0, preambleEnd).join("\n").trimEnd();

  /** @type {Item[]} */
  const items = [];
  /** @type {Item | null} */
  let cur = null;
  let inFields = false;
  /** @type {string[]} */
  let notes = [];
  const finish = () => {
    if (!cur) return;
    cur.notes = notes.join("\n").trim();
    items.push(cur);
  };
  for (const line of lines.slice(itemsAt + 1)) {
    const h = HEADING.exec(line);
    if (h) {
      finish();
      cur = {
        id: h[1],
        type: h[2],
        title: h[3].trim(),
        status: "inbox",
        prd: "",
        owner: "",
        commit: "",
        notes: "",
      };
      notes = [];
      inFields = true;
      continue;
    }
    if (!cur) continue; // text between "## Items" and the first item is dropped
    const f = inFields ? FIELD.exec(line) : null;
    if (f) {
      cur[f[1]] = f[2].trim();
      continue;
    }
    if (inFields && line.trim() === "") continue;
    inFields = false;
    notes.push(line);
  }
  finish();

  if (!opts.lenient) {
    const [dup] = duplicateIds(items);
    if (dup) throw new BacklogError(`${dup} appears twice in backlog.md (run pnpm backlog doctor)`);
  }
  return { preamble, items };
}

/** Ids that appear more than once. @param {{ id: string }[]} items */
export function duplicateIds(items) {
  const seen = new Set();
  const dups = new Set();
  for (const it of items) (seen.has(it.id) ? dups : seen).add(it.id);
  return [...dups];
}

/**
 * The summary table's rows as written in the file (not as `render` would write them).
 * @param {string} text @returns {{ id: string, row: string }[]}
 */
export function summaryRows(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((l) => l.trim() === SUMMARY);
  if (start < 0) return [];
  const rows = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === ITEMS) break;
    const m = /^\| (B-\d+) \|/.exec(line);
    if (m) rows.push({ id: m[1], row: line.trimEnd() });
  }
  return rows;
}

/** The summary rows `render` writes. @param {Backlog} b */
export const expectedSummaryRows = (b) =>
  [...b.items].sort((x, y) => num(x.id) - num(y.id)).map((i) => ({ id: i.id, row: summaryRow(i) }));

/** @param {Item} i */
const summaryRow = (i) =>
  `| ${i.id} | ${i.type} | ${i.status} | ${cell(i.prd)} | ${cell(i.owner)} | ${cell(i.title)} |`;

const cell = (s) => (s || "").replace(/\|/g, "\\|");

/** @param {Backlog} b @returns {string} */
export function render(b) {
  const items = [...b.items].sort((x, y) => num(x.id) - num(y.id));
  const rows = items.map(summaryRow);
  const blocks = items.map((i) =>
    [
      `### ${i.id} · ${i.type} · ${i.title}`,
      "",
      ...FIELDS.map((f) => `- ${f}: ${i[f]}`.trimEnd()),
      ...(i.notes ? ["", i.notes] : []),
    ].join("\n"),
  );
  return [
    b.preamble,
    "",
    SUMMARY,
    "",
    GENERATED,
    "",
    "| Id | Type | Status | PRD | Owner | Title |",
    "| -- | ---- | ------ | --- | ----- | ----- |",
    ...rows,
    "",
    ITEMS,
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

const num = (id) => Number(id.slice(2));

/**
 * The next free id: past every item, and past `b.reserved` (archived ids and
 * inbox tags), so an id is never given twice.
 * @param {Backlog & { reserved?: string[] }} b
 */
export const nextId = (b) =>
  `B-${[...b.items.map((i) => i.id), ...(b.reserved ?? [])].reduce((m, id) => Math.max(m, num(id)), 0) + 1}`;

/** @param {Backlog} b @param {string} id @returns {Item} */
export function find(b, id) {
  const norm = normId(id);
  const it = b.items.find((i) => i.id === norm);
  if (!it && b.archived?.includes(norm))
    throw new BacklogError(
      `${norm} is archived (plans/backlog-archive.md); pass --archived to change it there`,
    );
  if (!it) throw new BacklogError(`no item ${norm}`);
  return it;
}

/** "12", "b-12" → "B-12". @param {string} id */
export const normId = (id) => (/^\d+$/.test(id) ? `B-${id}` : id.toUpperCase());

/** @param {string} type */
export function checkType(type) {
  if (!TYPES.includes(type)) throw new BacklogError(`type must be one of ${TYPES.join(", ")}`);
}

/** @param {string} status */
export function checkStatus(status) {
  if (!STATUSES.includes(status)) throw new BacklogError(`status must be one of ${STATUSES.join(", ")}`);
}

/** @param {Backlog} b @param {{ type: string, title: string, prd?: string, status?: string, note?: string, by: string, date: string }} a */
export function add(b, a) {
  checkType(a.type);
  if (!a.title.trim()) throw new BacklogError("an item needs a title");
  const status = a.status ?? (a.prd ? "triaged" : "inbox");
  checkStatus(status);
  /** @type {Item} */
  const item = {
    id: nextId(b),
    type: a.type,
    title: a.title.trim(),
    status,
    prd: a.prd ?? "",
    owner: "",
    commit: "",
    notes: a.note ? noteLine(a.date, a.by, a.note) : "",
  };
  b.items.push(item);
  return item;
}

const noteLine = (date, by, text) => `- ${date} (${by}): ${text.trim()}`;

/** @param {Item} it @param {{ text: string, by: string, date: string }} a */
export function addNote(it, a) {
  if (!a.text.trim()) throw new BacklogError("empty note");
  it.notes = [it.notes, noteLine(a.date, a.by, a.text)].filter(Boolean).join("\n");
}

/** @param {Item} it @param {string} key @param {string} value */
export function setField(it, key, value) {
  if (key === "type") checkType(value);
  else if (key === "status") checkStatus(value);
  else if (key === "title") {
    if (!value.trim()) throw new BacklogError("an item needs a title");
  } else if (!FIELDS.includes(key)) {
    throw new BacklogError(`can't set "${key}" (use status, type, title, prd, owner or commit)`);
  }
  it[key] = value.trim();
}

/** Claim an item for `owner`; the first claim wins. @param {Item} it @param {string} owner @param {boolean} force */
export function claim(it, owner, force) {
  if (it.owner && it.owner !== owner && !force)
    throw new BacklogError(`${it.id} is already claimed by ${it.owner} (pass --force to take it)`);
  if (["live", "dropped"].includes(it.status)) throw new BacklogError(`${it.id} is ${it.status}`);
  it.owner = owner;
  if (["inbox", "triaged"].includes(it.status)) it.status = "in-progress";
}

/** @param {Item} it */
export function release(it) {
  it.owner = "";
  if (it.status === "in-progress") it.status = "triaged";
}

/**
 * The status an item with a commit has, given which branches contain it.
 * Manual statuses (inbox … in-progress, dropped) are left alone.
 * @param {Item} it @param {{ dev: boolean, staging: boolean, main: boolean }} has
 */
export function derive(it, has) {
  if (!it.commit || !DERIVED.includes(it.status)) return it.status;
  if (has.main) return "live";
  if (has.staging) return "staging";
  if (has.dev) return "landed";
  return "ready";
}

// ---- the inbox (plans/inbox.md): the user's plain list ----------------------
//
//   # Inbox
//   (instructions)
//   ## Bugs
//   - Login link can be clicked twice (B-1)      ← filed: tagged with its id
//   - The timeline jumps when I scroll           ← new: ingest files it
//     It happens on my phone.                    ← indented lines are details
//
// Ingest only ever appends " (B-<n>)" to a new bullet's first line, so the
// user's own wording and layout are never rewritten.

/** Heading words → item type. A heading that matches none files as "feature". */
const HEADING_TYPES = [
  [/bug/i, "bug"],
  [/question/i, "question"],
  [/plan|big/i, "plan"],
  [/chore|tooling|housekeeping/i, "chore"],
  [/change/i, "change"],
  [/feature|idea|request/i, "feature"],
];
const BULLET = /^[-*+] +(.*\S)\s*$/;
const TAG = /\s\((B-\d+)\)\s*$/;
const TITLE_MAX = 100;

/** @param {string} heading */
export const typeForHeading = (heading) => HEADING_TYPES.find(([re]) => re.test(heading))?.[1] ?? "feature";

/** @typedef {{ line: number, type: string, text: string, details: string, id: string | null }} InboxEntry */

/** Every top-level bullet under a "##" heading. @param {string} text @returns {InboxEntry[]} */
export function parseInbox(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  /** @type {InboxEntry[]} */
  const entries = [];
  let type = null;
  /** @type {InboxEntry | null} */
  let cur = null;
  let fence = false;
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence;
    if (fence) return;
    if (/^## /.test(line)) {
      type = typeForHeading(line.slice(3));
      cur = null;
      return;
    }
    if (/^#/.test(line)) {
      type = null; // the title, or a deeper heading: not a list
      cur = null;
      return;
    }
    const b = type ? BULLET.exec(line) : null;
    if (b) {
      const tag = TAG.exec(b[1]);
      cur = {
        line: i,
        type,
        text: tag ? b[1].slice(0, tag.index).trim() : b[1],
        details: "",
        id: tag?.[1] ?? null,
      };
      entries.push(cur);
      return;
    }
    if (cur && /^\s+\S/.test(line)) cur.details = [cur.details, line.trim()].filter(Boolean).join("\n");
    else if (line.trim() !== "") cur = null;
  });
  return entries;
}

/** The new (untagged, non-empty) bullets. @param {string} text */
export const newInboxEntries = (text) => parseInbox(text).filter((e) => !e.id && e.text.trim());

/** Append " (B-n)" to line `line`. @param {string} text @param {number} line @param {string} id */
export function tagInboxLine(text, line, id) {
  const lines = text.split("\n");
  lines[line] = `${lines[line].replace(/\s+$/, "")} (${id})`;
  return lines.join("\n");
}

/** A tracker title from a bullet: up to 100 characters, cut at a word. @param {string} text */
export function titleFromBullet(text) {
  const t = text.replace(/\s+/g, " ").trim();
  if (t.length <= TITLE_MAX) return t;
  const cut = t.slice(0, TITLE_MAX);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), 60))}…`;
}

/**
 * Remove the bullets tagged with any of `ids`, with their indented detail lines.
 * @param {string} text @param {string[]} ids
 */
export function removeInboxEntries(text, ids) {
  const want = new Set(ids);
  const lines = text.split("\n");
  const drop = new Set();
  for (const e of parseInbox(text)) {
    if (!e.id || !want.has(e.id)) continue;
    drop.add(e.line);
    // Details: indented lines, and blank lines between them.
    let last = e.line;
    for (let i = e.line + 1; i < lines.length; i++) {
      if (/^\s+\S/.test(lines[i])) last = i;
      else if (lines[i].trim() !== "") break;
    }
    for (let i = e.line + 1; i <= last; i++) drop.add(i);
  }
  // Collapse the blank lines a removal leaves behind (an emptied section's
  // two blanks become one, as Prettier would), so the inbox stays formatted.
  const kept = lines.filter((_, i) => !drop.has(i));
  const out = kept.filter((l, i) => !(drop.size && l.trim() === "" && i > 0 && kept[i - 1].trim() === ""));
  while (drop.size && out.length > 1 && out.at(-1) === "" && out.at(-2) === "") out.pop();
  return out.join("\n");
}

// ---- does an item's title come from its inbox bullet? -----------------------

const STOP_WORDS = new Set(
  "the and for with that this from into are was were but not you your our can should when then than have has its also all any".split(
    " ",
  ),
);
/** Content words, folded and lightly stemmed. @param {string} s */
const contentWords = (s) =>
  new Set(
    s
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .split(/[^a-z0-9]+/)
      .filter((w) => w.length >= 3 && !STOP_WORDS.has(w))
      .map((w) => w.replace(/(ing|ed|es|s)$/, "")),
  );

/**
 * Whether item `it` could have been filed from bullet `e` (fuzzy: agents
 * retitle items). True when the title is the bullet's, when ingest's
 * "From the inbox" note quotes it, or when the title shares at least two
 * content words, or a quarter of them, with the bullet and its details.
 * @param {InboxEntry} e @param {Item} it
 */
export function titleFromEntry(e, it) {
  const text = e.text.replace(/\s+/g, " ").trim();
  if (titleFromBullet(text) === it.title) return true;
  if (text && it.notes.replace(/\s+/g, " ").includes(`From the inbox: ${text}`)) return true;
  const title = contentWords(it.title);
  if (!title.size) return true;
  const source = contentWords(`${e.text} ${e.details}`);
  const shared = [...title].filter((w) => source.has(w)).length;
  return shared >= 2 || shared / title.size >= 0.25;
}

// ---- look-alikes ------------------------------------------------------------

/** How alike two texts must be (shared content words, 0 to 1) to count. */
export const SIMILAR_THRESHOLD = 0.6;
/** The most look-alikes shown for one text. */
export const SIMILAR_MAX = 5;

const foldedText = (/** @type {string} */ s) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

/** Twice the shared content words over both sizes; under two shared words is no match. */
function likeness(/** @type {Set<string>} */ a, /** @type {Set<string>} */ b) {
  const shared = [...a].filter((w) => b.has(w)).length;
  return shared < 2 ? 0 : (2 * shared) / (a.size + b.size);
}

/**
 * The items most like `text`, best first: the same words, or at least two
 * shared content words making up SIMILAR_THRESHOLD of both. A long bullet is
 * also compared by the title it would be filed under.
 * @param {string} text
 * @param {(Pick<Item, "id" | "status" | "prd" | "title"> & { archived?: boolean })[]} items
 * @returns {{ id: string, status: string, topic: string, title: string, archived: boolean, score: number }[]}
 */
export function similarItems(text, items) {
  const exact = foldedText(text);
  if (!exact) return [];
  const words = contentWords(text);
  const titleWords = contentWords(titleFromBullet(text));
  return items
    .map((it) => {
      const other = contentWords(it.title);
      const score =
        foldedText(it.title) === exact ? 1 : Math.max(likeness(words, other), likeness(titleWords, other));
      return {
        id: it.id,
        status: it.status,
        topic: it.prd,
        title: it.title,
        archived: !!it.archived,
        score,
      };
    })
    .filter((m) => m.score >= SIMILAR_THRESHOLD)
    .sort((a, b) => b.score - a.score || Number(a.id.slice(2)) - Number(b.id.slice(2)))
    .slice(0, SIMILAR_MAX);
}

/** One look-alike as a line. @param {ReturnType<typeof similarItems>[number]} m */
export const similarLine = (m) =>
  `${m.id}  ${m.status}${m.archived ? " (archived)" : ""}  ${m.topic || "no topic"}  ${m.title}`;
