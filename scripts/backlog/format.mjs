// Parse and render plans/backlog.md. Pure: no git, no file system.
//
// The file has three parts:
//   1. a preamble (title, how to use it, the PRD board): kept verbatim;
//   2. "## Summary": a table regenerated on every write;
//   3. "## Items": one block per item, in id order:
//
//      ### B-12 · bug · Sign-in can be submitted twice
//      - status: triaged
//      - prd: quick-fixes
//      - owner: prd/quick-fixes
//      - commit: 1a2b3c4
//
//      Free notes (any Markdown) until the next item.

export const TYPES = ["bug", "change", "feature", "plan", "question", "chore"];
export const STATUSES = ["inbox", "triaged", "in-progress", "ready", "landed", "staging", "live", "dropped"];
export const FIELDS = ["status", "prd", "owner", "commit"];
/** Statuses worked out from git once an item has a commit. */
export const DERIVED = ["ready", "landed", "staging", "live"];

const SUMMARY = "## Summary";
const ITEMS = "## Items";
const GENERATED = "<!-- Generated by `pnpm backlog` on every write: don't edit this table by hand. -->";
const HEADING = /^### (B-\d+) · (\S+) · (.*)$/;
const FIELD = new RegExp(`^- (${FIELDS.join("|")}):[ \\t]*(.*)$`);

export class BacklogError extends Error {}

/** @typedef {{ id: string, type: string, title: string, status: string, prd: string, owner: string, commit: string, notes: string }} Item */
/** @typedef {{ preamble: string, items: Item[] }} Backlog */

/** @param {string} text @returns {Backlog} */
export function parse(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const at = (h) => lines.findIndex((l) => l.trim() === h);
  const itemsAt = at(ITEMS);
  if (itemsAt < 0) throw new BacklogError(`backlog.md has no "${ITEMS}" heading`);
  const summaryAt = at(SUMMARY);
  const preambleEnd = summaryAt >= 0 && summaryAt < itemsAt ? summaryAt : itemsAt;
  const preamble = lines.slice(0, preambleEnd).join("\n").trimEnd();

  /** @type {Item[]} */
  const items = [];
  /** @type {Item | null} */
  let cur = null;
  let inFields = false;
  /** @type {string[]} */
  let notes = [];
  const finish = () => {
    if (!cur) return;
    cur.notes = notes.join("\n").trim();
    items.push(cur);
  };
  for (const line of lines.slice(itemsAt + 1)) {
    const h = HEADING.exec(line);
    if (h) {
      finish();
      cur = {
        id: h[1],
        type: h[2],
        title: h[3].trim(),
        status: "inbox",
        prd: "",
        owner: "",
        commit: "",
        notes: "",
      };
      notes = [];
      inFields = true;
      continue;
    }
    if (!cur) continue; // text between "## Items" and the first item is dropped
    const f = inFields ? FIELD.exec(line) : null;
    if (f) {
      cur[f[1]] = f[2].trim();
      continue;
    }
    if (inFields && line.trim() === "") continue;
    inFields = false;
    notes.push(line);
  }
  finish();

  const seen = new Set();
  for (const it of items) {
    if (seen.has(it.id)) throw new BacklogError(`${it.id} appears twice in backlog.md`);
    seen.add(it.id);
  }
  return { preamble, items };
}

const cell = (s) => (s || "").replace(/\|/g, "\\|");

/** @param {Backlog} b @returns {string} */
export function render(b) {
  const items = [...b.items].sort((x, y) => num(x.id) - num(y.id));
  const rows = items.map(
    (i) => `| ${i.id} | ${i.type} | ${i.status} | ${cell(i.prd)} | ${cell(i.owner)} | ${cell(i.title)} |`,
  );
  const blocks = items.map((i) =>
    [
      `### ${i.id} · ${i.type} · ${i.title}`,
      "",
      ...FIELDS.map((f) => `- ${f}: ${i[f]}`.trimEnd()),
      ...(i.notes ? ["", i.notes] : []),
    ].join("\n"),
  );
  return [
    b.preamble,
    "",
    SUMMARY,
    "",
    GENERATED,
    "",
    "| Id | Type | Status | PRD | Owner | Title |",
    "| -- | ---- | ------ | --- | ----- | ----- |",
    ...rows,
    "",
    ITEMS,
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

const num = (id) => Number(id.slice(2));

/** @param {Backlog} b */
export const nextId = (b) => `B-${b.items.reduce((m, i) => Math.max(m, num(i.id)), 0) + 1}`;

/** @param {Backlog} b @param {string} id @returns {Item} */
export function find(b, id) {
  const norm = /^\d+$/.test(id) ? `B-${id}` : id.toUpperCase();
  const it = b.items.find((i) => i.id === norm);
  if (!it) throw new BacklogError(`no item ${norm}`);
  return it;
}

/** @param {string} type */
export function checkType(type) {
  if (!TYPES.includes(type)) throw new BacklogError(`type must be one of ${TYPES.join(", ")}`);
}

/** @param {string} status */
export function checkStatus(status) {
  if (!STATUSES.includes(status)) throw new BacklogError(`status must be one of ${STATUSES.join(", ")}`);
}

/** @param {Backlog} b @param {{ type: string, title: string, prd?: string, status?: string, note?: string, by: string, date: string }} a */
export function add(b, a) {
  checkType(a.type);
  if (!a.title.trim()) throw new BacklogError("an item needs a title");
  const status = a.status ?? (a.prd ? "triaged" : "inbox");
  checkStatus(status);
  /** @type {Item} */
  const item = {
    id: nextId(b),
    type: a.type,
    title: a.title.trim(),
    status,
    prd: a.prd ?? "",
    owner: "",
    commit: "",
    notes: a.note ? noteLine(a.date, a.by, a.note) : "",
  };
  b.items.push(item);
  return item;
}

const noteLine = (date, by, text) => `- ${date} (${by}): ${text.trim()}`;

/** @param {Item} it @param {{ text: string, by: string, date: string }} a */
export function addNote(it, a) {
  if (!a.text.trim()) throw new BacklogError("empty note");
  it.notes = [it.notes, noteLine(a.date, a.by, a.text)].filter(Boolean).join("\n");
}

/** @param {Item} it @param {string} key @param {string} value */
export function setField(it, key, value) {
  if (key === "type") checkType(value);
  else if (key === "status") checkStatus(value);
  else if (key === "title") {
    if (!value.trim()) throw new BacklogError("an item needs a title");
  } else if (!FIELDS.includes(key)) {
    throw new BacklogError(`can't set "${key}" (use status, type, title, prd, owner or commit)`);
  }
  it[key] = value.trim();
}

/** Claim an item for `owner`; the first claim wins. @param {Item} it @param {string} owner @param {boolean} force */
export function claim(it, owner, force) {
  if (it.owner && it.owner !== owner && !force)
    throw new BacklogError(`${it.id} is already claimed by ${it.owner} (pass --force to take it)`);
  if (["live", "dropped"].includes(it.status)) throw new BacklogError(`${it.id} is ${it.status}`);
  it.owner = owner;
  if (["inbox", "triaged"].includes(it.status)) it.status = "in-progress";
}

/** @param {Item} it */
export function release(it) {
  it.owner = "";
  if (it.status === "in-progress") it.status = "triaged";
}

/**
 * The status an item with a commit has, given which branches contain it.
 * Manual statuses (inbox … in-progress, dropped) are left alone.
 * @param {Item} it @param {{ dev: boolean, staging: boolean, main: boolean }} has
 */
export function derive(it, has) {
  if (!it.commit || !DERIVED.includes(it.status)) return it.status;
  if (has.main) return "live";
  if (has.staging) return "staging";
  if (has.dev) return "landed";
  return "ready";
}
